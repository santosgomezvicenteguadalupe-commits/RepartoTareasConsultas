-- CREAMOS LA BASE DE DATOS
CREATE DATABASE IF NOT EXISTS `reparto_tareas` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci;

-- CREAMOS LAS DIFERENTES TABLAS QUE NECESITAMOS, ESPECIFICANDO LA BASE DE DATOS EN LA QUE SE VAN A CREAR
USE reparto_tareas;
-- EN ESTA TABLA SE ALMACENAN LAS PERSONAS QUE VAN A USAR LA APLICACIÓN
CREATE TABLE personas (
  idPersona tinyint(3) UNSIGNED AUTO_INCREMENT,
  nombrePersona varchar(15) NOT NULL,
  
  CONSTRAINT PK_ID_PERSONA PRIMARY KEY (idPersona)
);
-- EN ESTA TABLA SE ALMACENAN LAS DIFERENTES TAREAS QUE HAY QUE HACER EN EL PERIODO ESPECIFICADO
CREATE TABLE tareas (
  idTarea tinyint(3) UNSIGNED AUTO_INCREMENT,
  nombreTarea varchar(20) NOT NULL,
  
  CONSTRAINT PK_ID_TAREA PRIMARY KEY (idTarea)
);
-- EN ESTA TABLA SE HACE EL REPARTO DE TAREAS, SE ASOCIAN LAS PERSONAS CON LAS TAREAS EN UNA FECHA DETERMINADA
CREATE TABLE reparto (
  idTarea tinyint(3) UNSIGNED NOT NULL,
  idPersona tinyint(3) UNSIGNED NOT NULL,
  fecha DATE NOT NULL,
  
  CONSTRAINT PK_ID_REPARTO PRIMARY KEY (idPersona, fecha),
  CONSTRAINT UQ_TAREA_FECHA UNIQUE (idTarea, fecha),
  CONSTRAINT FK_ID_TAREA FOREIGN KEY (idTarea) REFERENCES tareas (idTarea),
  CONSTRAINT FK_ID_PERSONA FOREIGN KEY (idPersona) REFERENCES personas (idPersona) 
);
-- EN ESTA TABLA SE DETERMINA EL PERIODO DE TIEMPO EN EL QUE SE VAN A HACER LAS TAREAS
CREATE TABLE periodo(
  fechaInicio DATE NOT NULL,
  fechaFin DATE NOT NULL
);
-- EN ESTA TABLA PODEMOS HACER UNA PEQUEÑA LISTA DE LA COMPRA QUE ADEMÁS NOS PERMITE PROBAR EL DEFAULT
CREATE TABLE lista_compra(
  articulo varchar(50) NOT NULL,
  cantidad tinyint(3) NOT NULL DEFAULT 1
);

